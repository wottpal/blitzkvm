#!/usr/bin/env python3
"""Trains the app's 2x text upscaler (TextUpscaler.swift) and writes its
weights as Swift.

train.py DATA_DIR [--channels 8] [--steps 30000] [--swift OUT.swift]

DATA_DIR holds NNNNN_1x.png / NNNNN_2x.png pairs from gen.swift. The model
works on luma (BT.601 weights on sRGB-encoded values, as the app computes
it): 5x5 conv 1->C, two 3x3 convs C->C (ReLU), a 3x3 conv C->4 whose four
channels are pixel-shuffled into the 2x2 sub-pixels added to a bilinear 2x
enlargement. L1 loss on random 64x64 crops. With ../quality-bench/pattern.png
and pattern2x.png present it also scores the result against the native 2x
pattern (the regions the plan quotes).
"""
import glob, os, sys, time
import numpy as np
import torch, torch.nn as nn, torch.nn.functional as F
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.join(HERE, "..", "quality-bench")


def luma(path):
    a = np.asarray(Image.open(path).convert("RGB"), np.float32) / 255
    return 0.299 * a[..., 0] + 0.587 * a[..., 1] + 0.114 * a[..., 2]


class Upscaler(nn.Module):
    def __init__(self, c):
        super().__init__()
        self.c1 = nn.Conv2d(1, c, 5, padding=2)
        self.c2 = nn.Conv2d(c, c, 3, padding=1)
        self.c3 = nn.Conv2d(c, c, 3, padding=1)
        self.c4 = nn.Conv2d(c, 4, 3, padding=1)

    def forward(self, x):
        base = F.interpolate(x, scale_factor=2, mode="bilinear", align_corners=False)
        h = F.relu(self.c1(x))
        h = F.relu(self.c2(h))
        h = F.relu(self.c3(h))
        return base + F.pixel_shuffle(self.c4(h), 2)


# 1x regions of the test pattern: x0, y0, x1, y1.
REGIONS = {"light_text": (210, 40, 960, 520), "small_text": (210, 40, 960, 140), "dark_text": (960, 40, 1710, 380),
           "color_text": (210, 290, 960, 400), "code": (210, 410, 960, 470)}


def score(model, device):
    from skimage.metrics import structural_similarity as ssim
    one, two = os.path.join(BENCH, "pattern.png"), os.path.join(BENCH, "pattern2x.png")
    if not (os.path.exists(one) and os.path.exists(two)):
        return None
    truth = luma(two)
    with torch.no_grad():
        out = model(torch.from_numpy(luma(one))[None, None].to(device)).clamp(0, 1)[0, 0].cpu().numpy()
    result = {}
    for name, (x0, y0, x1, y1) in REGIONS.items():
        s, t = out[2 * y0:2 * y1, 2 * x0:2 * x1], truth[2 * y0:2 * y1, 2 * x0:2 * x1]
        result[name] = (round(float(10 * np.log10(1 / np.mean((s - t) ** 2))), 2), round(float(ssim(s, t, data_range=1.0)), 4))
    return result


def swift_source(model, channels, steps):
    def array(name, t):
        return f"    static let {name}: [Float] = [{', '.join(f'{x:.8g}' for x in t.detach().cpu().flatten().tolist())}]\n"
    src = (f"// Generated by tools/text-upscaler/train.py ({channels} channels, {steps} steps) from CoreText\n"
           "// 1x/2x pairs; do not edit. PyTorch layout: [out][in][kh][kw].\nenum TextUpscalerWeights {\n")
    for layer in ("c1", "c2", "c3", "c4"):
        conv = getattr(model, layer)
        src += array(f"{layer}Weight", conv.weight) + array(f"{layer}Bias", conv.bias)
    return src + "}\n"


def main():
    args = sys.argv[1:]
    data = args[0]
    channels = int(args[args.index("--channels") + 1]) if "--channels" in args else 8
    steps = int(args[args.index("--steps") + 1]) if "--steps" in args else 30000
    swift = args[args.index("--swift") + 1] if "--swift" in args else None
    device = torch.device("mps" if torch.backends.mps.is_available() else "cpu")
    pairs = sorted(glob.glob(os.path.join(data, "*_1x.png")))
    X = np.stack([luma(p) for p in pairs])
    Y = np.stack([luma(p.replace("_1x", "_2x")) for p in pairs])
    print("pairs", X.shape[0])
    torch.manual_seed(0)
    model = Upscaler(channels).to(device)
    opt = torch.optim.Adam(model.parameters(), lr=2e-3)
    schedule = torch.optim.lr_scheduler.CosineAnnealingLR(opt, steps)
    rng = np.random.default_rng(0)
    n, size, crop = X.shape[0], X.shape[1], 64
    start = time.time()
    for step in range(steps):
        idx, ox, oy = rng.integers(0, n, 64), rng.integers(0, size - crop, 64), rng.integers(0, size - crop, 64)
        xb = np.stack([X[i, y:y + crop, x:x + crop] for i, x, y in zip(idx, ox, oy)])[:, None]
        yb = np.stack([Y[i, 2 * y:2 * y + 2 * crop, 2 * x:2 * x + 2 * crop] for i, x, y in zip(idx, ox, oy)])[:, None]
        loss = F.l1_loss(model(torch.from_numpy(xb).to(device)), torch.from_numpy(yb).to(device))
        opt.zero_grad()
        loss.backward()
        opt.step()
        schedule.step()
        if step % 5000 == 0 or step == steps - 1:
            print(f"step {step} loss {loss.item():.5f} ({time.time() - start:.0f} s)", flush=True)
    print("against native 2x:", score(model, device))
    if swift:
        with open(swift, "w") as f:
            f.write(swift_source(model, channels, steps))
        print("wrote", swift)


if __name__ == "__main__":
    main()
