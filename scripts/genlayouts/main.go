// Command genlayouts generates pkg/input/layouts_gen.go from the keyboard
// layout tables of the upstream JetKVM web UI (jetkvm/kvm ui/src), so pasted
// text is typed exactly the way the official client types it.
//
//	go run ./scripts/genlayouts -upstream /path/to/jetkvm/kvm > pkg/input/layouts_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

type keyInfo struct {
	Key      string
	Shift    bool
	AltRight bool
}

type keyCombo struct {
	keyInfo
	DeadKey bool
	Accent  *keyInfo
}

func main() {
	upstream := flag.String("upstream", "", "path to a jetkvm/kvm checkout")
	ref := flag.String("ref", "", "upstream ref recorded in the generated header")
	flag.Parse()
	if *upstream == "" {
		fmt.Fprintln(os.Stderr, "missing -upstream")
		os.Exit(2)
	}
	src := filepath.Join(*upstream, "ui", "src")

	hid, err := parseHIDKeys(filepath.Join(src, "keyboardMappings.ts"))
	if err != nil {
		fail(err)
	}
	files, err := filepath.Glob(filepath.Join(src, "keyboardLayouts", "*.ts"))
	if err != nil {
		fail(err)
	}
	sort.Strings(files)

	layouts := map[string]map[string]keyCombo{}
	names := map[string]string{}
	codes := map[string]string{} // file stem (en_US) -> iso code (en-US)
	// Parse en_US first so spreads (...en_US.chars) resolve.
	sort.SliceStable(files, func(i, j int) bool { return strings.HasSuffix(files[i], "en_US.ts") })
	for _, f := range files {
		stem := strings.TrimSuffix(filepath.Base(f), ".ts")
		data, err := os.ReadFile(f)
		if err != nil {
			fail(err)
		}
		iso, name, chars, err := parseLayout(string(data), layouts, codes)
		if err != nil {
			fail(fmt.Errorf("%s: %w", f, err))
		}
		codes[stem] = iso
		layouts[iso] = chars
		names[iso] = name
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by scripts/genlayouts from jetkvm/kvm ui/src/keyboardLayouts%s. DO NOT EDIT.\n\n", refSuffix(*ref))
	buf.WriteString("package input\n\n")
	buf.WriteString("var generatedLayoutNames = map[string]string{\n")
	isos := make([]string, 0, len(layouts))
	for iso := range layouts {
		isos = append(isos, iso)
	}
	sort.Strings(isos)
	for _, iso := range isos {
		fmt.Fprintf(&buf, "\t%q: %q,\n", iso, names[iso])
	}
	buf.WriteString("}\n\n")
	buf.WriteString("var generatedLayouts = map[string]map[rune]charCombo{\n")
	for _, iso := range isos {
		fmt.Fprintf(&buf, "\t%q: {\n", iso)
		chars := layouts[iso]
		keys := make([]string, 0, len(chars))
		for ch := range chars {
			keys = append(keys, ch)
		}
		sort.Strings(keys)
		for _, ch := range keys {
			if utf8.RuneCountInString(ch) != 1 {
				continue // multi-rune entries cannot be typed from single runes
			}
			r, _ := utf8.DecodeRuneInString(ch)
			c := chars[ch]
			usage, ok := hid[c.Key]
			if !ok {
				// Upstream drops unknown key names too (keys[name] is undefined).
				fmt.Fprintf(os.Stderr, "warning: %s: skipping %q (unknown key %q)\n", iso, ch, c.Key)
				continue
			}
			fmt.Fprintf(&buf, "\t\t%s: {hid: 0x%02x, shift: %t, altRight: %t, deadKey: %t", runeLiteral(r), usage, c.Shift, c.AltRight, c.DeadKey)
			if c.Accent != nil {
				accent, ok := hid[c.Accent.Key]
				if !ok {
					// Upstream sends a key-less accent step, i.e. no accent.
					fmt.Fprintf(os.Stderr, "warning: %s: %q has unknown accent key %q, typing it unaccented\n", iso, ch, c.Accent.Key)
					buf.WriteString("},\n")
					continue
				}
				fmt.Fprintf(&buf, ", accent: &keyStroke{hid: 0x%02x, shift: %t, altRight: %t}", accent, c.Accent.Shift, c.Accent.AltRight)
			}
			buf.WriteString("},\n")
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		fail(err)
	}
	os.Stdout.Write(out)
}

func refSuffix(ref string) string {
	if ref == "" {
		return ""
	}
	return " @ " + ref
}

func runeLiteral(r rune) string {
	if r == '\'' {
		return `'\''`
	}
	if r == '\\' {
		return `'\\'`
	}
	if unicode.IsPrint(r) && r != utf8.RuneError {
		return "'" + string(r) + "'"
	}
	return fmt.Sprintf("'\\u%04x'", r)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

var hidLine = regexp.MustCompile(`^\s*([A-Za-z0-9_]+)\s*:\s*(0x[0-9a-fA-F]+|\d+)\s*,`)

func parseHIDKeys(path string) (map[string]int, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	text := string(data)
	start := strings.Index(text, "export const keys = {")
	if start < 0 {
		return nil, fmt.Errorf("keys map not found in %s", path)
	}
	out := map[string]int{}
	for _, line := range strings.Split(text[start:], "\n")[1:] {
		if strings.HasPrefix(strings.TrimSpace(line), "}") {
			break
		}
		m := hidLine.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		v, err := strconv.ParseInt(m[2], 0, 32)
		if err != nil {
			return nil, err
		}
		out[m[1]] = int(v)
	}
	return out, nil
}

var (
	isoRe    = regexp.MustCompile(`const isoCode = "([^"]+)"`)
	nameRe   = regexp.MustCompile(`const name = "([^"]+)"`)
	comboRe  = regexp.MustCompile(`const (\w+)\s*(?::\s*\w+)?\s*=\s*(\{[^}]*\})`)
	charsRe  = regexp.MustCompile(`(?m)^(?:export )?const chars(?:\s*:\s*[^=]+)?\s*=\s*\{`)
	spreadRe = regexp.MustCompile(`^\.\.\.(\w+?)(?:\.chars|_chars),?$`)
)

func parseLayout(text string, known map[string]map[string]keyCombo, codes map[string]string) (string, string, map[string]keyCombo, error) {
	iso := firstGroup(isoRe, text)
	name := firstGroup(nameRe, text)
	if iso == "" {
		return "", "", nil, fmt.Errorf("isoCode not found")
	}
	consts := map[string]keyInfo{}
	for _, m := range comboRe.FindAllStringSubmatch(text, -1) {
		info, err := parseKeyInfo(m[2], nil)
		if err == nil && info.Key != "" {
			consts[m[1]] = info.keyInfo
		}
	}
	loc := charsRe.FindStringIndex(text)
	if loc == nil {
		return "", "", nil, fmt.Errorf("chars not found")
	}
	body, err := braceBody(text, loc[1]-1)
	if err != nil {
		return "", "", nil, err
	}
	chars := map[string]keyCombo{}
	p := &parser{s: body}
	for {
		p.skipSpaceAndComments()
		if p.eof() {
			break
		}
		if strings.HasPrefix(p.rest(), "...") {
			line := p.readUntil(",\n")
			m := spreadRe.FindStringSubmatch(strings.TrimSpace(line))
			if m == nil {
				return "", "", nil, fmt.Errorf("unsupported spread %q", line)
			}
			base, ok := known[codes[m[1]]]
			if !ok {
				return "", "", nil, fmt.Errorf("spread of unknown layout %s", m[1])
			}
			for k, v := range base {
				chars[k] = v
			}
			p.consume(",")
			continue
		}
		key, err := p.readKey()
		if err != nil {
			return "", "", nil, err
		}
		p.skipSpaceAndComments()
		if !p.consume(":") {
			return "", "", nil, fmt.Errorf("expected ':' after %q", key)
		}
		p.skipSpaceAndComments()
		obj, err := p.readObject()
		if err != nil {
			return "", "", nil, fmt.Errorf("value of %q: %w", key, err)
		}
		combo, err := parseKeyInfo(obj, consts)
		if err != nil {
			return "", "", nil, fmt.Errorf("value of %q: %w", key, err)
		}
		chars[key] = combo
		p.skipSpaceAndComments()
		p.consume(",")
	}
	return iso, name, chars, nil
}

func firstGroup(re *regexp.Regexp, s string) string {
	m := re.FindStringSubmatch(s)
	if m == nil {
		return ""
	}
	return m[1]
}

// braceBody returns the text between the brace at open and its match.
func braceBody(s string, open int) (string, error) {
	depth := 0
	inStr := byte(0)
	for i := open; i < len(s); i++ {
		c := s[i]
		if inStr != 0 {
			if c == '\\' {
				i++
			} else if c == inStr {
				inStr = 0
			}
			continue
		}
		switch c {
		case '"', '\'':
			inStr = c
		case '/':
			if i+1 < len(s) && s[i+1] == '/' {
				for i < len(s) && s[i] != '\n' {
					i++
				}
			}
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return s[open+1 : i], nil
			}
		}
	}
	return "", fmt.Errorf("unbalanced braces")
}

var fieldRe = regexp.MustCompile(`(\w+)\s*:\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|true|false|\d+|\w+|\{[^}]*\})`)

func parseKeyInfo(obj string, consts map[string]keyInfo) (keyCombo, error) {
	var c keyCombo
	inner := strings.TrimSpace(obj)
	inner = strings.TrimPrefix(inner, "{")
	inner = strings.TrimSuffix(inner, "}")
	for _, m := range fieldRe.FindAllStringSubmatch(inner, -1) {
		field, value := m[1], m[2]
		switch field {
		case "key":
			c.Key = strings.Trim(value, `"'`)
		case "shift":
			c.Shift = value == "true"
		case "altRight":
			c.AltRight = value == "true"
		case "deadKey":
			c.DeadKey = value == "true"
		case "accentKey":
			if strings.HasPrefix(value, "{") {
				a, err := parseKeyInfo(value, consts)
				if err != nil {
					return c, err
				}
				c.Accent = &a.keyInfo
			} else {
				a, ok := consts[value]
				if !ok {
					return c, fmt.Errorf("unknown accent const %s", value)
				}
				c.Accent = &a
			}
		}
	}
	return c, nil
}

type parser struct {
	s   string
	pos int
}

func (p *parser) eof() bool    { return p.pos >= len(p.s) }
func (p *parser) rest() string { return p.s[p.pos:] }
func (p *parser) consume(t string) bool {
	if strings.HasPrefix(p.rest(), t) {
		p.pos += len(t)
		return true
	}
	return false
}

func (p *parser) readUntil(stops string) string {
	start := p.pos
	for !p.eof() && !strings.ContainsRune(stops, rune(p.s[p.pos])) {
		p.pos++
	}
	return p.s[start:p.pos]
}

func (p *parser) skipSpaceAndComments() {
	for !p.eof() {
		r, size := utf8.DecodeRuneInString(p.rest())
		switch {
		case unicode.IsSpace(r):
			p.pos += size
		case strings.HasPrefix(p.rest(), "//"):
			for !p.eof() && p.s[p.pos] != '\n' {
				p.pos++
			}
		case strings.HasPrefix(p.rest(), "/*"):
			end := strings.Index(p.rest(), "*/")
			if end < 0 {
				p.pos = len(p.s)
			} else {
				p.pos += end + 2
			}
		default:
			return
		}
	}
}

func (p *parser) readKey() (string, error) {
	if p.eof() {
		return "", fmt.Errorf("unexpected end")
	}
	q := p.s[p.pos]
	if q == '"' || q == '\'' {
		p.pos++
		var b strings.Builder
		for !p.eof() {
			c := p.s[p.pos]
			if c == q {
				p.pos++
				return b.String(), nil
			}
			if c == '\\' {
				r, n, err := unescape(p.rest())
				if err != nil {
					return "", err
				}
				b.WriteRune(r)
				p.pos += n
				continue
			}
			r, size := utf8.DecodeRuneInString(p.rest())
			b.WriteRune(r)
			p.pos += size
		}
		return "", fmt.Errorf("unterminated string")
	}
	start := p.pos
	for !p.eof() {
		r, size := utf8.DecodeRuneInString(p.rest())
		if r == ':' || unicode.IsSpace(r) {
			break
		}
		p.pos += size
	}
	if p.pos == start {
		return "", fmt.Errorf("empty key at %q", truncate(p.rest()))
	}
	return p.s[start:p.pos], nil
}

func (p *parser) readObject() (string, error) {
	if !strings.HasPrefix(p.rest(), "{") {
		return "", fmt.Errorf("expected object at %q", truncate(p.rest()))
	}
	body, err := braceBody(p.s, p.pos)
	if err != nil {
		return "", err
	}
	p.pos += len(body) + 2
	return "{" + body + "}", nil
}

// unescape decodes one JS escape sequence at the start of s.
func unescape(s string) (rune, int, error) {
	if len(s) < 2 {
		return 0, 0, fmt.Errorf("bad escape")
	}
	switch s[1] {
	case 'n':
		return '\n', 2, nil
	case 't':
		return '\t', 2, nil
	case 'r':
		return '\r', 2, nil
	case 'u':
		if strings.HasPrefix(s, `\u{`) {
			end := strings.IndexByte(s, '}')
			v, err := strconv.ParseUint(s[3:end], 16, 32)
			return rune(v), end + 1, err
		}
		v, err := strconv.ParseUint(s[2:6], 16, 32)
		return rune(v), 6, err
	case 'x':
		v, err := strconv.ParseUint(s[2:4], 16, 32)
		return rune(v), 4, err
	default:
		r, size := utf8.DecodeRuneInString(s[1:])
		return r, 1 + size, nil
	}
}

func truncate(s string) string {
	if len(s) > 40 {
		return s[:40]
	}
	return s
}
