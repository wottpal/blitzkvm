    ("da-DK", "com.apple.keylayout.Danish"),
    ("de-CH", "com.apple.keylayout.SwissGerman"),
    ("de-DE", "com.apple.keylayout.German"),
    ("en-UK", "com.apple.keylayout.British"),
    ("en-US", "com.apple.keylayout.US"),
    ("es-ES", "com.apple.keylayout.Spanish-ISO"),
    ("fr-CH", "com.apple.keylayout.SwissFrench"),
    ("fr-FR", "com.apple.keylayout.French"),
    ("hu-HU", "com.apple.keylayout.Hungarian"),
    ("it-IT", "com.apple.keylayout.Italian-Pro"),
    ("nb-NO", "com.apple.keylayout.Norwegian"),
    ("nl-BE", "com.apple.keylayout.Belgian"),
    ("pl-PL", "com.apple.keylayout.PolishPro"),
