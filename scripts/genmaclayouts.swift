/// The installer's characters (pkg/hostlink TypeSafe).
let charset = Array("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 !\"$%&/()=?+*#'-_.:,;")

/// Mac virtual key code → HID usage, for the keys that sit in the same place
/// on ANSI and ISO keyboards.
let keys: [(UInt16, UInt8)] = [
    (0x00, 0x04), (0x01, 0x16), (0x02, 0x07), (0x03, 0x09), (0x04, 0x0B), (0x05, 0x0A), (0x06, 0x1D), (0x07, 0x1B),
    (0x08, 0x06), (0x09, 0x19), (0x0B, 0x05), (0x0C, 0x14), (0x0D, 0x1A), (0x0E, 0x08), (0x0F, 0x15), (0x10, 0x1C),
    (0x11, 0x17), (0x12, 0x1E), (0x13, 0x1F), (0x14, 0x20), (0x15, 0x21), (0x16, 0x23), (0x17, 0x22), (0x18, 0x2E),
    (0x19, 0x26), (0x1A, 0x24), (0x1B, 0x2D), (0x1C, 0x25), (0x1D, 0x27), (0x1E, 0x30), (0x1F, 0x12), (0x20, 0x18),
    (0x21, 0x2F), (0x22, 0x0C), (0x23, 0x13), (0x25, 0x0F), (0x26, 0x0D), (0x27, 0x34), (0x28, 0x0E), (0x29, 0x33),
    (0x2A, 0x31), (0x2B, 0x36), (0x2C, 0x38), (0x2D, 0x11), (0x2E, 0x10), (0x2F, 0x37), (0x31, 0x2C),
]

/// Modifier states, plainest first: UCKeyTranslate's (EventModifiers >> 8)
/// and whether the stroke holds Shift and Option.
let modifiers: [(UInt32, Bool, Bool)] = [(0, false, false), (0x02, true, false), (0x08, false, true), (0x0A, true, true)]

func keyboardType(_ layoutType: Int) -> UInt32 {
    for type in UInt32(40)..<256 where Int(KBGetLayoutType(Int16(type))) == layoutType { return type }
    fatalError("no keyboard type for layout type \(layoutType)")
}

let ansi = keyboardType(kKeyboardANSI)
let iso = keyboardType(kKeyboardISO)

func layoutData(_ id: String) -> Data {
    let filter = [kTISPropertyInputSourceID as String: id] as CFDictionary
    guard let list = TISCreateInputSourceList(filter, true)?.takeRetainedValue() as? [TISInputSource],
          let source = list.first, let pointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else {
        fatalError("no keyboard layout \(id) on this Mac")
    }
    return Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
}

/// The character a key types, nil for a dead key or anything but one character.
func type(_ data: Data, key: UInt16, modifiers: UInt32, keyboard: UInt32) -> Character? {
    data.withUnsafeBytes { raw -> Character? in
        let layout = raw.baseAddress!.assumingMemoryBound(to: UCKeyboardLayout.self)
        var dead: UInt32 = 0
        var length = 0
        var chars = [UniChar](repeating: 0, count: 4)
        guard UCKeyTranslate(layout, key, UInt16(kUCKeyActionDown), modifiers, keyboard, 0, &dead, 4, &length, &chars) == noErr,
              dead == 0, length == 1 else { return nil }
        return Character(String(utf16CodeUnits: chars, count: 1))
    }
}

func hex(_ value: UInt8) -> String { String(format: "0x%02x", value) }

func literal(_ c: Character) -> String {
    switch c {
    case "'": return "'\\''"
    case "\\": return "'\\\\'"
    default: return "'\(c)'"
    }
}

let version = ProcessInfo.processInfo.operatingSystemVersionString
var out = """
    // Code generated by scripts/genmaclayouts.swift from the keyboard layouts of macOS \(version). DO NOT EDIT.

    package input

    // macLayoutSources names the Mac input source each table comes from.
    var macLayoutSources = map[string]string{

    """
for (code, id) in sources { out += "\t\"\(code)\": \"\(id)\",\n" }
out += "}\n\n// macLayouts: how a Mac with that input source types each character.\nvar macLayouts = map[string]map[rune]keyStroke{\n"
for (code, id) in sources {
    let data = layoutData(id)
    out += "\t\"\(code)\": {\n"
    for char in charset {
        search: for (state, shift, option) in modifiers {
            for (key, hid) in keys {
                let onANSI = type(data, key: key, modifiers: state, keyboard: ansi)
                if onANSI == char && type(data, key: key, modifiers: state, keyboard: iso) == char {
                    out += "\t\t\(literal(char)): {hid: \(hex(hid)), shift: \(shift), altRight: \(option)},\n"
                    break search
                }
            }
        }
    }
    out += "\t},\n"
}
out += "}\n"
print(out, terminator: "")
