// genmaclayouts generates pkg/input/maclayouts_gen.go from the keyboard
// layouts macOS ships, read with UCKeyTranslate: for each JetKVM keyboard
// layout, how a Mac with the matching input source types the characters
// clipboard sync's installer uses (pkg/hostlink TypeSafe). The JetKVM's own
// tables (layouts_gen.go) follow Windows, and on a Mac many characters sit
// on other keys.
//
//	swift scripts/genmaclayouts.swift > pkg/input/maclayouts_gen.go
//
// A key counts only when it types the character, without a dead key, the
// same way on ANSI and ISO keyboards. The two keys macOS swaps on ISO
// keyboards (§ and `) are left out: which one the JetKVM's keyboard is
// depends on how the Mac classified it.
